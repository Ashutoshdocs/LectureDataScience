"""Lecture 15: Operator overloading: arithmetic, reflected ops, NotImplemented, total_ordering, __hash__."""
import functools
import math

print("=== 1. A Vector with arithmetic operators ===")


class Vector:
    def __init__(self, x, y):
        self.x, self.y = x, y

    def __repr__(self):
        return f"Vector({self.x}, {self.y})"

    def __add__(self, other):
        if not isinstance(other, Vector):
            return NotImplemented
        return Vector(self.x + other.x, self.y + other.y)

    def __sub__(self, other):
        if not isinstance(other, Vector):
            return NotImplemented
        return Vector(self.x - other.x, self.y - other.y)

    def __mul__(self, k):
        if not isinstance(k, (int, float)):
            return NotImplemented
        return Vector(self.x * k, self.y * k)

    __rmul__ = __mul__                       # 3 * v  -> v.__rmul__(3)

    def __neg__(self):
        return Vector(-self.x, -self.y)

    def __abs__(self):
        return math.hypot(self.x, self.y)

    def __eq__(self, other):
        if not isinstance(other, Vector):
            return NotImplemented
        return (self.x, self.y) == (other.x, other.y)

    def __hash__(self):
        return hash((self.x, self.y))


a, b = Vector(2, 3), Vector(1, 1)
print("  a + b  =", a + b, "| a - b =", a - b, "| -a =", -a)
print("  a * 3  =", a * 3, "| 3 * a =", 3 * a, "<- needs __rmul__")
print("  abs(Vector(3, 4)) =", abs(Vector(3, 4)))
print("  a + b == Vector(3, 4):", a + b == Vector(3, 4))
print("  a unchanged after all that:", a)
c = a
c += b                                       # no __iadd__ -> falls back to a = a + b (new object)
print("  c += b gives a new object:", c, "| a is still", a)
for expr, func in [("a + 5", lambda: a + 5), ("a * a", lambda: a * a)]:
    try:
        func()
    except TypeError as e:
        print(f"  {expr} -> TypeError: {e}")

print("\n=== 2. Money: rules inside operators, sum() support ===")


class Money:
    def __init__(self, amount, currency="INR"):
        self.amount, self.currency = round(amount, 2), currency

    def __repr__(self):
        return f"{self.currency} {self.amount:,.2f}"

    def __add__(self, other):
        if isinstance(other, Money):
            if other.currency != self.currency:
                raise ValueError(f"can't add {self.currency} and {other.currency}")
            return Money(self.amount + other.amount, self.currency)
        return NotImplemented

    def __radd__(self, other):              # sum() starts with 0 + first_item
        if other == 0:
            return self
        return self.__add__(other)

    def __mul__(self, k):
        return Money(self.amount * k, self.currency) if isinstance(k, (int, float)) else NotImplemented

    __rmul__ = __mul__

    def __truediv__(self, parts):
        return Money(self.amount / parts, self.currency)


bill = [Money(250), Money(120.5), Money(99.99)]
total = sum(bill)
print("  sum(bill)          =", total)
print("  total * 1.18 (tax) =", total * 1.18)
print("  split 3 ways       =", total / 3)
try:
    Money(10) + Money(5, "USD")
except ValueError as e:
    print("  INR + USD -> ValueError:", e)

print("\n=== 3. Comparisons with @total_ordering ===")


@functools.total_ordering
class Version:
    def __init__(self, text):
        self.text = text
        self.parts = tuple(int(p) for p in text.split("."))

    def __repr__(self):
        return f"v{self.text}"

    def __eq__(self, other):
        return self.parts == other.parts if isinstance(other, Version) else NotImplemented

    def __lt__(self, other):
        return self.parts < other.parts if isinstance(other, Version) else NotImplemented


versions = [Version("1.10.2"), Version("1.9"), Version("2.0"), Version("1.10")]
print("  sorted:", sorted(versions))
print("  1.10 > 1.9 :", Version("1.10") > Version("1.9"), "(string comparison would say", "1.10" > "1.9", ")")
print("  >= and <= generated by total_ordering:", Version("2.0") >= Version("2.0"), Version("1.0") <= Version("0.9"))
print("  max:", max(versions))

print("\n=== 4. __eq__ without __hash__ breaks sets and dicts ===")


class PointNoHash:
    def __init__(self, x, y):
        self.x, self.y = x, y

    def __eq__(self, other):
        return (self.x, self.y) == (other.x, other.y)


print("  PointNoHash.__hash__ is", PointNoHash.__hash__)
try:
    {PointNoHash(1, 2)}
except TypeError as e:
    print("  {PointNoHash(1, 2)} -> TypeError:", e)
print("  Vector has __hash__: len({Vector(1,2), Vector(1,2)}) =", len({Vector(1, 2), Vector(1, 2)}))
