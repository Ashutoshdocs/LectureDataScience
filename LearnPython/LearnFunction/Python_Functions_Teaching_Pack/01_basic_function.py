"""
MODULE 1: BASIC FUNCTION

A function is a reusable block of code that performs a task.
The `def` keyword defines a function.
Defining a function does not execute its body.
The body runs when we call the function.
"""

# STEP 1: Define the function.
def greet():
    print("Welcome to Python!")
    print("We are learning functions.")
    print("Functions make code reusable.")


# STEP 2: Call the function.
greet()

# Calling the same function again reuses the same code.
greet()
