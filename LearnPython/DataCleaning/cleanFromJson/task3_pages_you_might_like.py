"""
TASK 3 - Find "Pages You Might Like".

Input:
    outputs/clean_social_data.json

Output:
    outputs/pages_you_might_like.csv

Logic:
    Users who like some of the same pages may share interests.
    Recommend other pages liked by those users.
    The bonus score also considers pages liked by direct friends.
"""

import json
from pathlib import Path
from collections import Counter

import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
INPUT_FILE = BASE_DIR / "outputs" / "clean_social_data.json"
OUTPUT_DIR = BASE_DIR / "outputs"
OUTPUT_DIR.mkdir(exist_ok=True)

# Load the cleaned network generated by Task 1.
with INPUT_FILE.open(encoding="utf-8") as file:
    data = json.load(file)

users = {
    user["id"]: user
    for user in data["users"]
}

# Convert relationship lists to sets for set intersection and difference.
friends_of = {
    user_id: set(user["friends"])
    for user_id, user in users.items()
}

likes_of = {
    user_id: set(user["liked_pages"])
    for user_id, user in users.items()
}

name_of = {
    user_id: user["name"]
    for user_id, user in users.items()
}

clean_pages = {
    page["id"]: page["name"]
    for page in data["pages"]
}


def pages_you_might_like(user_id, top_n=5):
    """
    Recommend pages based on similar users' interests.

    A user who shares more liked pages with us contributes a higher score.
    Pages we already like are not suggested.
    """
    my_pages = likes_of[user_id]
    scores = Counter()

    # Compare the selected user with every other user.
    for other_user_id, other_pages in likes_of.items():

        # Do not compare the user with themselves.
        if other_user_id == user_id:
            continue

        # Count how many pages both users have liked.
        shared_page_count = len(my_pages & other_pages)

        if shared_page_count == 0:
            continue

        # Add the shared-interest score to pages we have not liked yet.
        new_pages = other_pages - my_pages

        for page_id in new_pages:
            scores[page_id] += shared_page_count

    return scores.most_common(top_n)


def pages_you_might_like_v2(user_id, top_n=5, friend_weight=1):
    """
    Bonus recommendation method.

    Start with similar-interest scores, then add extra points for pages
    liked by direct friends. friend_weight controls the extra points.
    """
    # Get all interest-based scores (top_n=None means do not limit yet).
    scores = Counter(dict(pages_you_might_like(user_id, top_n=None)))

    # Give an additional score to pages liked by direct friends.
    for friend_id in friends_of[user_id]:
        new_friend_pages = likes_of[friend_id] - likes_of[user_id]

        for page_id in new_friend_pages:
            scores[page_id] += friend_weight

    return scores.most_common(top_n)


# ---------------------------------------------------------
# Example: show page suggestions for Amit (user ID 1)
# ---------------------------------------------------------
selected_user = 1

if selected_user not in users:
    raise ValueError(f"User ID {selected_user} does not exist in cleaned data.")

already_liked = [
    clean_pages[page_id]
    for page_id in sorted(likes_of[selected_user])
]

print(f"{name_of[selected_user]} already likes: {already_liked}")
print(f"\nPages {name_of[selected_user]} might like:")

for page_id, score in pages_you_might_like(selected_user):
    print(f"  {clean_pages[page_id]:<25} - score {score}")

print(f"\nPages {name_of[selected_user]} might like (interests + friends):")

for page_id, score in pages_you_might_like_v2(selected_user):
    print(f"  {clean_pages[page_id]:<25} - score {score}")

# ---------------------------------------------------------
# Generate top page suggestions for every user
# ---------------------------------------------------------
recommendation_rows = []

for user_id in sorted(likes_of):
    top_pages = pages_you_might_like_v2(user_id, top_n=3)

    suggestion_text = ", ".join(
        clean_pages[page_id]
        for page_id, score in top_pages
    )

    recommendation_rows.append({
        "user_id": user_id,
        "user": name_of[user_id],
        "pages_you_might_like": suggestion_text or "—",
    })

recommendations_df = pd.DataFrame(recommendation_rows)

output_file = OUTPUT_DIR / "pages_you_might_like.csv"
recommendations_df.to_csv(output_file, index=False)

print("\nPage recommendations for all users:")
print(recommendations_df.head(10))
print(f"\nSaved: {output_file}")
